import Foundation
import ProfileKit
import SecondScreen
import Testing

@testable import FeaturesPhone

/// Codes from the TV via the system camera: **on-device test 2026-09-27, T3.**
///
/// The camera opens only schemes that the app has registered. And what it opens must be
/// the same code that the reader in the app would accept — no more and no less.
@Suite("Code entry")
struct CodeEntryTests {

    @Test("A handoff code leads into the handoff")
    func handoff() throws {
        let text = HandoffKey.fresh(target: "LivingRoom").asText(schema: HandoffKey.schema)
        let url = try #require(URL(string: text))
        #expect(CodeEntry.from(url) == .handoff(text))
    }

    @Test("A pairing code leads into the remote")
    func remotePairing() throws {
        let text = HandoffKey.fresh(target: "LivingRoom").asText(schema: RemotePairing.schema)
        let url = try #require(URL(string: text))
        #expect(CodeEntry.from(url) == .remotePairing(text))
    }

    @Test("A profile link leads into adopting the profile")
    func profile() throws {
        let link = ProfileLink(
            approval: try #require(URL(string: "https://www.icloud.com/share/0abc")), person: "Alex")
        #expect(CodeEntry.from(link.url) == .profile(link))
    }

    /// On-device finding 2026-09-30: the TV's code "Get from iPhone".
    @Test("A profile pairing code leads into the profile, without a second scan")
    func profilePairing() {
        let url = Pairing.link(code: Pairing.code(), role: .search)
        #expect(CodeEntry.from(url) == .pairing(url.absoluteString))
    }

    @Test("Foreign links lead nowhere")
    func foreign() throws {
        #expect(CodeEntry.from(try #require(URL(string: "https://example.com/?k=abc"))) == nil)
        #expect(CodeEntry.from(try #require(URL(string: "cinelounge-uebergabe://LivingRoom"))) == nil)
    }

    /// **Without registration with the system the camera opens nothing** — exactly the finding. Both
    /// schemes must be in the Info.plist, otherwise the code above is correct
    /// and still unreachable.
    ///
    /// Read from `project.yml` and not from `App/Info.plist`: the plist is generated by
    /// XcodeGen and ignored by Git, so on a fresh clone (and in the public export) it does not
    /// exist until the first `xcodegen` run — the check then failed for a missing file and not
    /// for a missing scheme. `project.yml` is what the plist is generated from.
    @Test("Both schemes are registered with the system")
    func signedIn() throws {
        let project = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("project.yml")
        let schemata = Self.urlSchemes(inProject: try String(contentsOf: project, encoding: .utf8))
        try #require(!schemata.isEmpty, "project.yml must register URL schemes")
        #expect(schemata.contains(HandoffKey.schema))
        #expect(schemata.contains(RemotePairing.schema))
        #expect(schemata.contains(ProfileLink.schema))
        #expect(schemata.contains(Pairing.cameraScheme))
        #expect(!schemata.contains(Pairing.schema), "the old scheme stays an open entry")
    }

    /// The list items under every `CFBundleURLSchemes:` key — only keys, not the same word
    /// inside a comment. Comment lines between the items are skipped, the list ends at the
    /// first line that is neither.
    private static func urlSchemes(inProject text: String) -> Set<String> {
        var schemes = Set<String>()
        var inList = false
        for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.hasPrefix("CFBundleURLSchemes:") {
                inList = true
            } else if inList, trimmed.hasPrefix("- ") {
                schemes.insert(String(trimmed.dropFirst(2)).trimmingCharacters(in: .whitespaces))
            } else if inList, trimmed.hasPrefix("#") {
                continue
            } else {
                inList = false
            }
        }
        return schemes
    }
}
