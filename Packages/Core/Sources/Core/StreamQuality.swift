import Foundation

/// An upper limit for the bitrate that the viewer sets themselves.
///
/// **Why this is no subtlety:** on 2026-09-06 measurements were taken from
/// the phone through the tunnel, four times in an hour, with **one**
/// difference — the location:
///
/// | Time | Where | Throughput | Latency |
/// |---|---|---|---|
/// | 19:56 | in a dead zone | 0.61 Mbit/s | 348 ms |
/// | 20:00 | in a dead zone | 0.51 Mbit/s | 81 ms |
/// | 20:12 | in a dead zone | **0.28 Mbit/s** | 87 ms |
/// | 20:54 | outdoors | **7.34 Mbit/s** | 66 ms |
///
/// **Twenty-six to one, and the difference is a change of place.** That is the
/// stronger version of the finding and not the weaker: it is no noise that
/// could be averaged away but a state that one **enters and leaves** — in the
/// middle of a running film.
///
/// **That also explains the old number.** For years this said "measured 0.3
/// Mbit/s" as a property of the tunnel; the measurement at 20:12 hit it to
/// two places. It was never wrong — it was **the bad end of a range**,
/// measured in a bad place, that somebody took for a constant.
///
/// **And the narrowness is not the tunnel.** On the same device and in the
/// same minutes the ordinary internet connection carried 0.54 to 0.69 Mbit/s.
/// The home connection pushes out a measured **16.8 Mbit/s** (2026-09-06, against
/// a remote server) — at 7.34 on the phone it is not the bottleneck. What is
/// missing is missing in the radio cell.
///
/// **Exactly for that reason the ladder is right — and a fixed setting would
/// not be.** Whoever sets 0.3 sees a picture of blocks at 20:54 although
/// 1080p would have gone through; whoever sets 8 sees a spinner at 20:12.
/// Both ends occur, in one evening, without warning. The automatic mode is
/// therefore the normal case and this enumeration the exception for whoever
/// knows better.
///
/// The automatic mode recognises too little bandwidth only **after** it has
/// collapsed. Whoever knows they are on the move wants to be able to say so
/// beforehand.
///
/// The limit is a limit and not a target value: a title that is below it on
/// its own is not artificially scaled up.
// **`Hashable` and `Codable` were added on 2026-09-08** — for ``Downloads/Job``,
// which has to carry a chosen level across a restart. For an enumeration over
// `String` both cost nothing and are generated by the compiler; what they
// spare is a second field with the same content in text form and the
// conversion at each end.
public enum StreamQuality: String, Sendable, Hashable, Codable, CaseIterable, Identifiable {

    /// Nothing is limited — the right thing on the home network.
    case unlimited
    /// 20 Mbit/s. Enough for 4K on a decent line.
    case veryHigh
    /// 8 Mbit/s. Sauberes 1080p.
    case high
    /// 4 Mbit/s. 1080p with visible compromises in motion.
    case medium
    /// 2 Mbit/s. 720p, for on the move over mobile data.
    case low
    /// 0.5 Mbit/s. Looks bad and plays — that is the point.
    case minimal

    public var id: String { rawValue }

    /// The upper limit in bits per second, or `nil` for unlimited.
    public var bitrate: Int? {
        switch self {
        case .unlimited: nil
        case .veryHigh: 20_000_000
        case .high: 8_000_000
        case .medium: 4_000_000
        case .low: 2_000_000
        case .minimal: 500_000
        }
    }

    /// The picture width matching the limit.
    ///
    /// Must be passed along, because a limit alone does not help: whoever
    /// squeezes 4K into 2 Mbit/s gets a picture of blocks. Fewer pixels at the
    /// same amount of data look clearly better.
    public var maxWidth: Int? {
        switch self {
        case .unlimited: nil
        case .veryHigh: 3840
        case .high: 1920
        case .medium: 1920
        case .low: 1280
        case .minimal: 854
        }
    }

    // MARK: - Gemessene Leitung in eine Stufe übersetzen

    /// The highest level that still fits into a measured bandwidth.
    ///
    /// This is needed when the app measures the line itself instead of asking the
    /// viewer. **The reason for this detour via a level** — instead of taking
    /// the measured number directly as the limit: every level has a matching
    /// picture width attached. A limit without width is the trap described above
    /// at ``maxWidth`` — 4K squeezed into two megabit gives a picture of blocks
    /// although the number is right.
    ///
    /// It does not round up: whoever measured 7 Mbit/s gets the level for 4, not
    /// the one for 8. The measurement is a snapshot, and over the course of a
    /// film the line tends to get worse rather than better.
    public static func fitting(_ measuredBitrate: Int) -> StreamQuality {
        // From top to bottom, so that the first level that fits is also the highest
        // that fits.
        for step in [veryHigh, high, medium, low] where (step.bitrate ?? 0) <= measuredBitrate {
            return step
        }
        // Under two megabit only the lowest level remains. It looks bad and plays —
        // at the 0.28 Mbit/s measured on 2026-09-06 on mobile data, that is the
        // difference between a picture and a spinner.
        //
        // **And even it is not enough there.** The lowest level is at 0.5, the worst
        // measurement at 0.28 — at this end no level helps any more, only the
        // downloads. A sixth level below would be a picture nobody wants to look at,
        // and the claim that it works after all.
        return minimal
    }

    /// The stricter of two limits.
    ///
    /// Both paths can apply at the same time: the viewer has set a level, **and**
    /// the measurement says the line carries even less. Then the smaller one
    /// applies — taking the larger would mean silently ignoring one of the two
    /// statements.
    public func stricter(than other: StreamQuality) -> StreamQuality {
        switch (bitrate, other.bitrate) {
        case (nil, _): other
        case (_, nil): self
        case (let mine?, let theirs?): mine <= theirs ? self : other
        }
    }

    // MARK: - Ablage

    static let storageKey = "playback.quality"

    public static func load(from store: any KeyValueStore) -> StreamQuality {
        guard let raw = try? store.value(for: storageKey), let value = StreamQuality(rawValue: raw)
        else {
            // One starts on the home network, and there every limit is a loss.
            return .unlimited
        }
        return value
    }

    public func save(to store: any KeyValueStore) {
        if self == .unlimited {
            try? store.remove(Self.storageKey)
        } else {
            try? store.set(rawValue, for: Self.storageKey)
        }
    }
}
